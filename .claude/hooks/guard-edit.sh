#!/usr/bin/env bash
# PreToolUse hook for Edit/Write/MultiEdit — protect sensitive files.
#
# Project settings.json `permissions.deny` covers most via gitignore-style rules.
# This hook adds runtime checks for resolved/symlinked paths and pattern edge cases.

set -uo pipefail

HOOK_NAME="guard-edit"
. "${CLAUDE_PROJECT_DIR}/.claude/hooks/_common.sh"
read_input

PATH_FIELD="$(tool_input_field 'file_path')"
[ -z "$PATH_FIELD" ] && PATH_FIELD="$(tool_input_field 'path')"
[ -z "$PATH_FIELD" ] && exit 0

log "$PATH_FIELD"

# Resolve to absolute path (best effort — file may not yet exist for Write)
ABS_PATH="$PATH_FIELD"
case "$ABS_PATH" in
  /*) ;;
  ~/*) ABS_PATH="${HOME}${ABS_PATH#~}" ;;
  *)  ABS_PATH="$(pwd)/${ABS_PATH}" ;;
esac

# .env files
case "$ABS_PATH" in
  *"/.env"|*"/.env."*|*"/.envrc"|*"/.env.local"|*"/.env.production"|*"/.env.development")
    block "Refused edit to .env file: $ABS_PATH. Use a secret store or .env.example template."
    ;;
esac

# Git internals (NOT .gitignore / .gitattributes / .github/)
case "$ABS_PATH" in
  *"/.git/"*) block "Refused edit inside .git/: $ABS_PATH." ;;
esac

# SSH and credentials in $HOME
case "$ABS_PATH" in
  "$HOME/.ssh/"*|"$HOME/.aws/"*|"$HOME/.gnupg/"*|"$HOME/.kube/"*|"$HOME/.git-credentials")
    block "Refused edit to credential file: $ABS_PATH."
    ;;
esac

# Lock files — must be regenerated by package manager, not hand-edited
case "$ABS_PATH" in
  */package-lock.json|*/yarn.lock|*/pnpm-lock.yaml|*/Gemfile.lock|*/Pipfile.lock|*/poetry.lock|*/Cargo.lock|*/go.sum)
    block "Refused direct edit to lockfile: $(basename "$ABS_PATH"). Use the package manager."
    ;;
esac

# Conventional secrets dirs
case "$ABS_PATH" in
  */secrets/*|*/private/*|*/.secrets/*)
    block "Refused edit inside secrets/ folder: $ABS_PATH."
    ;;
esac

exit 0
